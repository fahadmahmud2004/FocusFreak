#!/usr/bin/env python3
"""Exports U8g2 fonts to Dart, so the virtual bot draws the same pixels as the OLED.

    python3 tools/make_fonts.py [path/to/u8g2_fonts.c]

Reads the fonts straight out of the U8g2 Arduino library (the one the firmware
compiles against), decodes U8g2's run-length glyph format and writes
`focusfreak_app/lib/botos/fonts.g.dart`. A glyph there is the exact bitmap
`drawStr` puts on the SSD1309, so text on the phone and text on the desk match
to the pixel.

Only the fonts in FONTS are exported. Add one there and re-run; do not edit the
generated Dart.
"""

import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
DEFAULT_SRC = os.path.expanduser(
    "~/Documents/Arduino/libraries/U8g2/src/clib/u8g2_fonts.c")
OUT = os.path.join(HERE, "..", "focusfreak_app", "lib", "botos", "fonts.g.dart")

# Dart name -> U8g2 font. The roles follow Flipper Zero's 128x64 UI, the best
# studied screen of this size: a bold primary face, a small secondary one, a
# monospace, and big numerals.
FONTS = {
    "primary": "u8g2_font_helvB08_tr",
    "secondary": "u8g2_font_haxrcorp4089_tr",
    "mono": "u8g2_font_profont11_tr",
    "tiny": "u8g2_font_4x6_tr",
    "body": "u8g2_font_6x10_tr",
    "big24": "u8g2_font_logisoso24_tn",
    "big32": "u8g2_font_logisoso32_tn",
    "big16": "u8g2_font_logisoso16_tn",
}


def load_font(src, name):
    m = re.search(
        r"const uint8_t " + re.escape(name) + r"\[\d+\][^=]*=\s*((?:\s*\"(?:[^\"\\]|\\.)*\")+)\s*;",
        src,
    )
    if not m:
        sys.exit(f"font {name} not found")
    out = bytearray()
    for lit in re.findall(r"\"((?:[^\"\\]|\\.)*)\"", m.group(1)):
        i = 0
        while i < len(lit):
            c = lit[i]
            if c != "\\":
                out.append(ord(c))
                i += 1
                continue
            n = lit[i + 1]
            if n in "01234567":
                j = i + 1
                while j < len(lit) and j < i + 4 and lit[j] in "01234567":
                    j += 1
                out.append(int(lit[i + 1:j], 8))
                i = j
            else:
                out.append({"n": 10, "t": 9, "r": 13, "\\": 92, "\"": 34, "'": 39,
                            "a": 7, "b": 8, "f": 12, "v": 11, "?": 63}[n])
                i += 2
    return bytes(out)


class Bits:
    def __init__(self, data, pos):
        self.data = data
        self.pos = pos
        self.bit = 0

    def u(self, cnt):
        val = self.data[self.pos] >> self.bit
        total = self.bit + cnt
        if total >= 8:
            s = 8 - self.bit
            self.pos += 1
            val |= self.data[self.pos] << s
            total -= 8
        val &= (1 << cnt) - 1
        self.bit = total
        return val

    def s(self, cnt):
        return self.u(cnt) - (1 << (cnt - 1))


def decode(font):
    h = font
    info = dict(
        count=h[0], bits0=h[2], bits1=h[3], bw=h[4], bh=h[5], bx=h[6], by=h[7],
        bd=h[8], ascent=h[13] - 256 if h[13] > 127 else h[13],
        descent=h[14] - 256 if h[14] > 127 else h[14],
    )
    glyphs = {}
    p = 23
    while p < len(font):
        enc, jump = font[p], font[p + 1]
        if jump == 0:
            break
        b = Bits(font, p + 2)
        w = b.u(info["bw"])
        hh = b.u(info["bh"])
        x = b.s(info["bx"])
        y = b.s(info["by"])
        dx = b.s(info["bd"])
        rows = [0] * hh
        if w > 0:
            cx = cy = 0

            def run(length, on):
                nonlocal cx, cy
                while length > 0:
                    take = min(length, w - cx)
                    if on:
                        for k in range(take):
                            rows[cy] |= 1 << (cx + k)
                    cx += take
                    length -= take
                    if cx >= w:
                        cx = 0
                        cy += 1

            while True:
                a = b.u(info["bits0"])
                c = b.u(info["bits1"])
                while True:
                    run(a, False)
                    run(c, True)
                    if b.u(1) == 0:
                        break
                if cy >= hh:
                    break
        glyphs[enc] = (w, hh, x, y, dx, rows[:hh])
        p += jump
    return info, glyphs


def main():
    path = sys.argv[1] if len(sys.argv) > 1 else DEFAULT_SRC
    src = open(path, encoding="latin-1").read()
    lines = [
        "// GENERATED by tools/make_fonts.py from the U8g2 library.",
        "// Do not edit by hand. U8g2 fonts are BSD/public domain licensed, see",
        "// the U8g2 repository for each font's terms.",
        "//",
        "// ignore_for_file: lines_longer_than_80_chars",
        "",
        "part of 'gfx.dart';",
        "",
    ]
    for dart, name in FONTS.items():
        info, glyphs = decode(load_font(src, name))
        lines.append(f"/// `{name}`")
        lines.append(f"const BotFont _{dart} = BotFont(")
        lines.append(f"  ascent: {info['ascent']},")
        lines.append(f"  descent: {info['descent']},")
        lines.append("  glyphs: <int, BotGlyph>{")
        for enc in sorted(glyphs):
            w, hh, x, y, dx, rows = glyphs[enc]
            lines.append(
                f"    {enc}: BotGlyph({w}, {hh}, {x}, {y}, {dx}, <int>[{', '.join(map(str, rows))}]),")
        lines.append("  },")
        lines.append(");")
        lines.append("")
        print(f"{dart:14} {name:40} {len(glyphs):3} glyphs  ascent {info['ascent']}")
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w") as f:
        f.write("\n".join(lines))
    print("wrote", os.path.relpath(OUT))


if __name__ == "__main__":
    main()
